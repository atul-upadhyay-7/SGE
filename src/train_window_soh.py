"""
train_window_soh.py
-------------------
Train the partial-window (BMS-visible) SOH model and save it under
models/ so the backend estimator can load it, plus a per-discharge
prediction fixture for B0005 that pins the backend to this pipeline
to within a rounding error.

The input is features.WINDOW_MODEL_FEATURES: the 4.0-3.4 V window
quantities made relative to the cell's own first-five-discharge
baseline (or already scale-free, capacity per amp). Those quantities
are measurable from a partial discharge, so the model needs no full
cycle and no first-cycle capacity reference. It is trained on every
audited cell, across all three operating groups, which is what lets
the cell-relative ratios transfer.

Outputs
    models/soh_window_all.joblib          fitted sklearn Pipeline bundle
    models/soh_window_all.ubj + .json     portable copy the estimator loads
    data/processed/soh_window_predictions_B0005.csv
                                          per-discharge predictions, the
                                          backend test's reference

The CSV is generated by the *same* features.window_model_row call the
backend estimator makes and scored by the same portable booster, so
test_window_estimator.py can compare the two directly.
"""

from pathlib import Path

import joblib
import pandas as pd

import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))

from evaluation import build_model  # noqa: E402
from features import (  # noqa: E402
    WINDOW_FEATURES,
    WINDOW_MODEL_FEATURES,
    WINDOW_REFERENCE_WINDOW,
    window_model_row,
)
from predict import load_portable_bundle  # noqa: E402
from repro import rounded  # noqa: E402
from run_experiments import cell_relative_features  # noqa: E402
from train_soh import _save_portable  # noqa: E402

PROC = Path("data/processed")
MODEL_DIR = Path("models")

CLEAN = PROC / "nasa_ml_dataset_clean.csv"
TARGET = "soh"
FIXTURE_CELL = "B0005"

MODEL_NAME = "soh_window_all"


def _fixture_rows(df):

    cell = df[df["cell_id"] == FIXTURE_CELL].sort_values(
        "discharge_index"
    )

    early = [
        df.loc[index].to_dict()
        for index in cell.head(WINDOW_REFERENCE_WINDOW).index
    ]

    return cell, early


def main():

    df = pd.read_csv(CLEAN)

    data = cell_relative_features(df)

    features = list(WINDOW_MODEL_FEATURES)

    cell, early = _fixture_rows(df)

    # The vectorised training columns and the scalar inference builder
    # must agree on the fixture cell, or the estimator would score the
    # model on inputs it was never trained on.
    worst = 0.0

    for index, row in cell.iterrows():

        built = window_model_row(df.loc[index], early)

        for name in features:

            worst = max(
                worst, abs(built[name] - float(data.loc[index, name]))
            )

    print(
        "feature agreement on "
        f"{FIXTURE_CELL}: max abs diff {worst:.3e}"
    )

    if worst > 1e-9:

        raise SystemExit(
            "window_model_row disagrees with cell_relative_features "
            f"on {FIXTURE_CELL} by {worst:.3e}"
        )

    model = build_model("XGBoost")

    model.fit(data[features], data[TARGET])

    MODEL_DIR.mkdir(parents=True, exist_ok=True)

    trained_on = sorted(data["cell_id"].unique().tolist())

    joblib.dump(
        {
            "model": model,
            "features": features,
            "target": TARGET,
            "trained_on": trained_on,
        },
        MODEL_DIR / f"{MODEL_NAME}.joblib",
    )

    _save_portable(
        model, features, TARGET, trained_on, MODEL_DIR / MODEL_NAME
    )

    bundle = load_portable_bundle(MODEL_DIR / f"{MODEL_NAME}.ubj")
    portable = bundle["model"]

    rows = []

    for index, raw in cell.iterrows():

        built = window_model_row(df.loc[index], early)

        predicted = float(
            portable.predict(
                pd.DataFrame([built])[bundle["features"]]
            )[0]
        )

        record = {
            "cell_id": raw["cell_id"],
            "discharge_index": int(raw["discharge_index"]),
            "soh": float(raw[TARGET]),
        }

        for name in WINDOW_FEATURES:

            record[name] = float(raw[name])

        record["current_mean"] = float(raw["current_mean"])
        record["predicted_soh"] = predicted

        rows.append(record)

    out = PROC / (
        f"soh_window_predictions_{FIXTURE_CELL}.csv"
    )

    rounded(pd.DataFrame(rows)).to_csv(out, index=False)

    print(
        f"trained on {len(trained_on)} cells, "
        f"{len(data)} discharges"
    )
    print(f"wrote {MODEL_DIR / MODEL_NAME}.joblib (+ .ubj/.json)")
    print(f"wrote {out} ({len(rows)} rows)")


if __name__ == "__main__":

    main()
