"""
train_window_soh.py
-------------------
Train the partial-window (BMS-visible) SOH model and save it under
models/ so the backend estimator can load it, plus two B0005 fixtures
that keep a regression check apart from an accuracy number.

The input is features.WINDOW_MODEL_FEATURES: the 4.0-3.4 V window
quantities made relative to the cell's own first-five-discharge
baseline (or already scale-free, capacity per amp). Those quantities
are measurable from a partial discharge, so the model needs no full
cycle and no first-cycle capacity reference. It is trained on every
audited cell, across all three operating groups, which is what lets
the cell-relative ratios transfer.

Two models are saved, and they answer different questions:

  * ``soh_window_all`` — the deployable estimator's model, trained on
    every audited cell. Scoring it on B0005 is *in-sample*: the cell
    was in its training set, so the error there only proves the
    pipeline is deterministic, not how well the model predicts.
    Its per-discharge output is
    ``data/processed/soh_window_regression_B0005.csv``, an in-sample
    regression check, not accuracy.
  * ``soh_window_no_B0005`` — the same feature contract trained
    WITHOUT B0005 (on the other cells of B0005's own operating group,
    matching the report's leave-one-cell-out: G1 protocol). Its
    per-discharge B0005 output, ``soh_window_heldout_B0005.csv``, is
    the held-out number the report quotes.

Outputs
    models/soh_window_all.joblib          fitted sklearn Pipeline bundle
    models/soh_window_all.ubj + .json     portable copy the estimator loads
    data/processed/soh_window_regression_B0005.csv
                                          in-sample regression check, not
                                          accuracy; the backend test's
                                          reference for the estimator
    models/soh_window_no_B0005.joblib     the same fit without B0005
    models/soh_window_no_B0005.ubj + .json
    data/processed/soh_window_heldout_B0005.csv
                                          held-out B0005 predictions from
                                          the model that never saw it

The regression CSV is generated by the *same* features.window_model_row
call the backend estimator makes and scored by the same portable booster,
so test_window_estimator.py can compare the two directly.
"""

import sys
from pathlib import Path

import joblib
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

from evaluation import build_model  # noqa: E402
from features import (  # noqa: E402
    WINDOW_FEATURES,
    WINDOW_MODEL_FEATURES,
    WINDOW_REFERENCE_WINDOW,
    window_model_row,
)
from predict import load_portable_bundle  # noqa: E402
from repro import rounded  # noqa: E402
from run_experiments import (  # noqa: E402
    GROUP_COL,
    cell_relative_features,
)
from train_soh import _save_portable  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

PROC = ROOT / "data/processed"
MODEL_DIR = ROOT / "models"

CLEAN = PROC / "nasa_ml_dataset_clean.csv"
TARGET = "soh"
FIXTURE_CELL = "B0005"

MODEL_NAME = "soh_window_all"

# The model that never saw the fixture cell. It is trained on the
# other cells of the fixture's own operating group, which is the
# report's leave-one-cell-out: G1 split, so its B0005 error is the
# same held-out number the report table quotes.
HELDOUT_MODEL_NAME = "soh_window_no_B0005"

REGRESSION_CSV = PROC / "soh_window_regression_B0005.csv"
HELDOUT_CSV = PROC / "soh_window_heldout_B0005.csv"


def _fixture_rows(df):

    cell = df[df["cell_id"] == FIXTURE_CELL].sort_values(
        "discharge_index"
    )

    early = [
        df.loc[index].to_dict()
        for index in cell.head(WINDOW_REFERENCE_WINDOW).index
    ]

    return cell, early


def _heldout_train(df):

    group = df.loc[
        df["cell_id"] == FIXTURE_CELL, GROUP_COL
    ].iloc[0]

    return df[
        (df[GROUP_COL] == group) & (df["cell_id"] != FIXTURE_CELL)
    ]


def _prediction_frames(df, cell, early, features):
    """
    Per-discharge rows for the fixture cell: the target, the raw
    window inputs the backend sees, and the model inputs for scoring.
    """

    built = {
        index: window_model_row(df.loc[index], early)
        for index, _ in cell.iterrows()
    }

    return built


def _feature_ranges(frame, features):
    """
    The [min, max] each model feature was trained across, written into
    the bundle so the estimator can refuse an input outside the range
    (widened by features.WINDOW_RANGE_SLACK) rather than score it.
    """

    return {
        name: (float(frame[name].min()), float(frame[name].max()))
        for name in features
    }


def _raw_columns(raw):

    record = {
        "cell_id": raw["cell_id"],
        "discharge_index": int(raw["discharge_index"]),
        "soh": float(raw[TARGET]),
    }

    for name in WINDOW_FEATURES:

        record[name] = float(raw[name])

    record["current_mean"] = float(raw["current_mean"])

    return record


def main():

    df = pd.read_csv(CLEAN)

    data = cell_relative_features(df)

    features = list(WINDOW_MODEL_FEATURES)

    cell, early = _fixture_rows(df)

    # The vectorised training columns and the scalar inference builder
    # must agree on the fixture cell, or the estimator would score the
    # model on inputs it was never trained on.
    worst = 0.0

    for index, row in cell.iterrows():

        built = window_model_row(df.loc[index], early)

        for name in features:

            worst = max(
                worst, abs(built[name] - float(data.loc[index, name]))
            )

    print(
        "feature agreement on "
        f"{FIXTURE_CELL}: max abs diff {worst:.3e}"
    )

    if worst > 1e-9:

        raise SystemExit(
            "window_model_row disagrees with cell_relative_features "
            f"on {FIXTURE_CELL} by {worst:.3e}"
        )

    built = _prediction_frames(df, cell, early, features)

    MODEL_DIR.mkdir(parents=True, exist_ok=True)

    # ---- The deployable model: every audited cell --------------------
    model = build_model("XGBoost")

    model.fit(data[features], data[TARGET])

    trained_on = sorted(data["cell_id"].unique().tolist())

    feature_ranges = _feature_ranges(data, features)

    joblib.dump(
        {
            "model": model,
            "features": features,
            "target": TARGET,
            "trained_on": trained_on,
            "feature_ranges": {
                name: list(bounds) for name, bounds in feature_ranges.items()
            },
        },
        MODEL_DIR / f"{MODEL_NAME}.joblib",
    )

    _save_portable(
        model, features, TARGET, trained_on, MODEL_DIR / MODEL_NAME,
        feature_ranges=feature_ranges,
    )

    bundle = load_portable_bundle(MODEL_DIR / f"{MODEL_NAME}.ubj")
    portable = bundle["model"]

    # In-sample regression fixture: scored by the portable booster so
    # the backend estimator can be pinned to it, but labelled as the
    # regression check it is. This is NOT an accuracy number.
    rows = []

    for index, raw in cell.iterrows():

        record = _raw_columns(raw)

        record["predicted_soh"] = float(
            portable.predict(
                pd.DataFrame([built[index]])[bundle["features"]]
            )[0]
        )

        rows.append(record)

    rounded(pd.DataFrame(rows)).to_csv(REGRESSION_CSV, index=False)

    # ---- The held-out model: B0005 removed ---------------------------
    train = _heldout_train(df)

    xgb = build_model("XGBoost")
    xgb.fit(data.loc[train.index, features], data.loc[train.index, TARGET])

    trained_on_heldout = sorted(train["cell_id"].unique().tolist())

    heldout_ranges = _feature_ranges(data.loc[train.index], features)

    joblib.dump(
        {
            "model": xgb,
            "features": features,
            "target": TARGET,
            "trained_on": trained_on_heldout,
            "feature_ranges": {
                name: list(bounds)
                for name, bounds in heldout_ranges.items()
            },
        },
        MODEL_DIR / f"{HELDOUT_MODEL_NAME}.joblib",
    )

    _save_portable(
        xgb, features, TARGET, trained_on_heldout,
        MODEL_DIR / HELDOUT_MODEL_NAME,
        feature_ranges=heldout_ranges,
    )

    en = build_model("ElasticNet")
    en.fit(data.loc[train.index, features], data.loc[train.index, TARGET])

    heldout_rows = []

    for index, raw in cell.iterrows():

        record = {
            "cell_id": raw["cell_id"],
            "discharge_index": int(raw["discharge_index"]),
            "soh": float(raw[TARGET]),
        }

        matrix = pd.DataFrame([built[index]])[features]

        record["predicted_elasticnet"] = float(en.predict(matrix)[0])
        record["predicted_xgboost"] = float(xgb.predict(matrix)[0])

        heldout_rows.append(record)

    heldout = pd.DataFrame(heldout_rows)

    heldout_rounded = rounded(heldout)

    heldout_rounded.to_csv(HELDOUT_CSV, index=False)

    truth = heldout["soh"]

    for column, label in (
        ("predicted_elasticnet", "ElasticNet"),
        ("predicted_xgboost", "XGBoost"),
    ):

        mae = float((truth - heldout[column]).abs().mean())

        print(
            f"held-out {FIXTURE_CELL} ({label}): MAE {mae:.4f}% "
            f"over {len(heldout)} discharges"
        )

    print(
        f"trained on {len(trained_on)} cells, "
        f"{len(data)} discharges"
    )
    print(
        f"held-out model trained on {len(trained_on_heldout)} cells: "
        f"{', '.join(trained_on_heldout)}"
    )
    print(f"wrote {MODEL_DIR / MODEL_NAME}.joblib (+ .ubj/.json)")
    print(f"wrote {MODEL_DIR / HELDOUT_MODEL_NAME}.joblib (+ .ubj/.json)")
    print(f"wrote {REGRESSION_CSV} ({len(rows)} rows, in-sample)")
    print(f"wrote {HELDOUT_CSV} ({len(heldout)} rows, held-out)")


if __name__ == "__main__":

    main()
