#!/usr/bin/env python
"""
make_alert_rules.py
-------------------
Generate the Grafana alert rules from the data, not from a
hand-typed number.

The one committed constant that used to be typed by hand was the
temperature bound (55 C). That number was a guess: the alert title
is "Inputs Outside Trained Operational Range", so the bound must be
the range the SOH model actually trained on. This script reads
data/processed/nasa_ml_dataset_clean.csv and writes the peak-
temperature maximum of that dataset into the rule, so the alert can
never disagree with the training data.

It writes the same file to both provisioning trees, because the two
deployment paths use different roots:

  docker/grafana/provisioning/alerting/alert_rules.yml    (docker compose)
  dashboard/provisioning/alerting/alert_rules.yml         (native Grafana)

Each rule is a three-node pipeline, the shape Grafana's unified
alerting expects:

  A  query      the datasource series (the JSON API target)
  B  reduce     collapse the series to its last value
  C  threshold  compare that value to the bound; `condition` is C

The old rules skipped the reduce node and put the threshold straight
on the query, which Grafana cannot reduce to a single value for a
multi-point series. The condition is always the last node in `data`.
"""

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
PROC = ROOT / "data" / "processed"

CLEAN = PROC / "nasa_ml_dataset_clean.csv"

OUTPUTS = [
    ROOT / "docker" / "grafana" / "provisioning" / "alerting" / "alert_rules.yml",
    ROOT / "dashboard" / "provisioning" / "alerting" / "alert_rules.yml",
]

RETIRE_SOH_PCT = 80.0

# Recent cycles only. The rules are evaluated every minute, so a
# one-hour window is enough history to reduce to the latest reading;
# the old 24 h window loaded far more points than the rule used.
WINDOW_SECONDS = 3600

TEMPLATE = """\
# Generated by scripts/make_alert_rules.py — do not edit by hand.
#
# The temperature bound is the maximum peak temperature in the clean
# training dataset ({temp:.4f} C), read from nasa_ml_dataset_clean.csv.
# Every rule is query -> reduce(last) -> threshold(condition).
apiVersion: 1

groups:
  - orgId: 1
    name: battery_pdm_alerts
    folder: Battery PDM
    interval: 1m
    rules:
      - uid: alert_soh_below_threshold
        title: Battery SOH Below Retirement Threshold
        condition: C
        data:
          - refId: A
            queryType: ""
            relativeTimeRange:
              from: {window}
              to: 0
            datasourceUid: battery-pdm-ds
            model:
              target: live_soh_by_cycle
          - refId: B
            queryType: ""
            datasourceUid: __expr__
            model:
              type: reduce
              expression: A
              reducer: last
          - refId: C
            queryType: ""
            datasourceUid: __expr__
            model:
              type: threshold
              expression: B
              conditions:
                - evaluator:
                    params: [{retire}]
                    type: lt
        noDataState: OK
        execErrState: OK
        for: 0s
        annotations:
          summary: Battery cell SOH has dropped below the {retire:.0f}% retirement threshold.
        labels:
          severity: critical

      - uid: alert_input_out_of_range
        title: Inputs Outside Trained Operational Range
        condition: C
        data:
          - refId: A
            queryType: ""
            relativeTimeRange:
              from: {window}
              to: 0
            datasourceUid: battery-pdm-ds
            model:
              target: live_temperature_by_cycle
          - refId: B
            queryType: ""
            datasourceUid: __expr__
            model:
              type: reduce
              expression: A
              reducer: last
          - refId: C
            queryType: ""
            datasourceUid: __expr__
            model:
              type: threshold
              expression: B
              conditions:
                - evaluator:
                    params: [{temp:.4f}]
                    type: gt
        noDataState: OK
        execErrState: OK
        for: 0s
        annotations:
          summary: Cell peak temperature exceeds the {temp:.4f} C maximum the SOH model trained on.
        labels:
          severity: warning
"""


def trained_peak_temperature_c():
    """Maximum peak temperature in the clean SOH training dataset."""

    df = pd.read_csv(CLEAN)

    if "temperature_max" not in df.columns:

        raise SystemExit(
            f"{CLEAN} has no 'temperature_max' column; "
            "regenerate the dataset with src/preprocessing.py"
        )

    value = float(df["temperature_max"].max())

    if not value == value:  # NaN

        raise SystemExit(f"{CLEAN} has no finite temperature_max values")

    return value


def build_rules(temp):
    """
    The rule spec, as data, so scripts/check_alerts.py can evaluate
    the exact same conditions against the live series without
    parsing YAML.

    direction is the operator for `value <op> threshold`:
    "lt" fires below (SOH retirement), "gt" fires above (a
    temperature the model never trained on).
    """

    return [
        {
            "uid": "alert_soh_below_threshold",
            "title": "Battery SOH Below Retirement Threshold",
            "target": "live_soh_by_cycle",
            "direction": "lt",
            "threshold": RETIRE_SOH_PCT,
        },
        {
            "uid": "alert_input_out_of_range",
            "title": "Inputs Outside Trained Operational Range",
            "target": "live_temperature_by_cycle",
            "direction": "gt",
            "threshold": temp,
        },
    ]


def render(temp):
    return TEMPLATE.format(
        temp=temp,
        retire=RETIRE_SOH_PCT,
        window=WINDOW_SECONDS,
    )


def main():

    temp = trained_peak_temperature_c()

    text = render(temp)

    for path in OUTPUTS:

        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)

        print(f"wrote {path.relative_to(ROOT)}")

    print(
        f"temperature bound: {temp:.4f} C "
        f"(max peak temperature in {CLEAN.name})"
    )


if __name__ == "__main__":

    main()
