#!/usr/bin/env python
"""
make_alert_rules.py
-------------------
Generate the Grafana alert rules from the data, not from a
hand-typed number.

Two things used to be wrong and are fixed here:

  * the query datasource was simpod-json-datasource, whose plugin
    declares "alerting": false, so Grafana's alerting engine could
    never evaluate the rules ([plugin.unavailable]). The rules now
    query the provisioned Prometheus datasource (uid
    battery-pdm-prom), which is a backend datasource with alerting
    support and is fed by dashboard/alert_exporter.py;
  * noDataState and execErrState were OK, which hides a datasource
    that is down or erroring. They are Alerting for every rule, so a
    rule that cannot read its input reports a problem instead of
    looking healthy.

The temperature bound is still read from
data/processed/nasa_ml_dataset_clean.csv: the alert title is "Inputs
Outside Trained Operational Range", so the bound must be the range
the SOH model actually trained on (the maximum peak temperature),
never a hand-typed constant.

It writes the same file to both provisioning trees, because the two
deployment paths use different roots:

  docker/grafana/provisioning/alerting/alert_rules.yml    (docker compose)
  dashboard/provisioning/alerting/alert_rules.yml         (native Grafana)

Each rule is a three-node pipeline, the shape Grafana's unified
alerting expects:

  A  query      the Prometheus metric (battery_pdm_cell_*)
  B  reduce     collapse the series to its last value
  C  threshold  compare that value to the bound; `condition` is C
"""

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
PROC = ROOT / "data" / "processed"

CLEAN = PROC / "nasa_ml_dataset_clean.csv"

OUTPUTS = [
    ROOT / "docker" / "grafana" / "provisioning" / "alerting" / "alert_rules.yml",
    ROOT / "dashboard" / "provisioning" / "alerting" / "alert_rules.yml",
]

# The alert path goes through Prometheus, not the JSON-datasource
# plugin (whose "alerting" is false). Keep these in step with the
# provisioned datasource in docker/grafana/provisioning/datasources.
ALERT_DATASOURCE_UID = "battery-pdm-prom"

RETIRE_SOH_PCT = 80.0

# Recent cycles only. The rules are evaluated every minute, so a
# one-hour window is enough history to reduce to the latest reading.
WINDOW_SECONDS = 3600

# Prometheus metric names served by dashboard/alert_exporter.py.
SOH_METRIC = "battery_pdm_cell_soh_percent"
TEMP_METRIC = "battery_pdm_cell_peak_temperature_celsius"

TEMPLATE = """\
# Generated by scripts/make_alert_rules.py — do not edit by hand.
#
# The temperature bound is the maximum peak temperature in the clean
# training dataset ({temp:.4f} C), read from nasa_ml_dataset_clean.csv.
# Every rule is query -> reduce(last) -> threshold(condition).
#
# The query datasource is Prometheus (uid {ds}), not the JSON-datasource
# plugin, because that plugin declares "alerting": false and Grafana's
# alerting engine cannot evaluate it. noDataState and execErrState are
# Alerting so a dead datasource is visible, not silently OK.
apiVersion: 1

groups:
  - orgId: 1
    name: battery_pdm_alerts
    folder: Battery PDM
    interval: 1m
    rules:
      - uid: alert_soh_below_threshold
        title: Battery SOH Below Retirement Threshold
        condition: C
        data:
          - refId: A
            queryType: ""
            relativeTimeRange:
              from: {window}
              to: 0
            datasourceUid: {ds}
            model:
              editorMode: code
              expr: {soh_metric}
              instant: false
              range: true
          - refId: B
            queryType: ""
            datasourceUid: __expr__
            model:
              type: reduce
              expression: A
              reducer: last
          - refId: C
            queryType: ""
            datasourceUid: __expr__
            model:
              type: threshold
              expression: B
              conditions:
                - evaluator:
                    params: [{retire}]
                    type: lt
        noDataState: Alerting
        execErrState: Alerting
        for: 0s
        annotations:
          summary: Battery cell SOH has dropped below the {retire:.0f}% retirement threshold.
        labels:
          severity: critical

      - uid: alert_input_out_of_range
        title: Inputs Outside Trained Operational Range
        condition: C
        data:
          - refId: A
            queryType: ""
            relativeTimeRange:
              from: {window}
              to: 0
            datasourceUid: {ds}
            model:
              editorMode: code
              expr: {temp_metric}
              instant: false
              range: true
          - refId: B
            queryType: ""
            datasourceUid: __expr__
            model:
              type: reduce
              expression: A
              reducer: last
          - refId: C
            queryType: ""
            datasourceUid: __expr__
            model:
              type: threshold
              expression: B
              conditions:
                - evaluator:
                    params: [{temp:.4f}]
                    type: gt
        noDataState: Alerting
        execErrState: Alerting
        for: 0s
        annotations:
          summary: Cell peak temperature exceeds the {temp:.4f} C maximum the SOH model trained on.
        labels:
          severity: warning
"""


def trained_peak_temperature_c():
    """Maximum peak temperature in the clean SOH training dataset."""

    df = pd.read_csv(CLEAN)

    if "temperature_max" not in df.columns:

        raise SystemExit(
            f"{CLEAN} has no 'temperature_max' column; "
            "regenerate the dataset with src/preprocessing.py"
        )

    value = float(df["temperature_max"].max())

    if not value == value:  # NaN

        raise SystemExit(f"{CLEAN} has no finite temperature_max values")

    return value


def build_rules(temp):
    """
    The rule spec, as data, so tests and tools can read the exact
    conditions without parsing YAML.

    `expr` is the PromQL metric the query node asks Prometheus for;
    direction is the operator for `value <op> threshold`:
    "lt" fires below (SOH retirement), "gt" fires above (a
    temperature the model never trained on).
    """

    return [
        {
            "uid": "alert_soh_below_threshold",
            "title": "Battery SOH Below Retirement Threshold",
            "expr": SOH_METRIC,
            "direction": "lt",
            "threshold": RETIRE_SOH_PCT,
            "datasourceUid": ALERT_DATASOURCE_UID,
        },
        {
            "uid": "alert_input_out_of_range",
            "title": "Inputs Outside Trained Operational Range",
            "expr": TEMP_METRIC,
            "direction": "gt",
            "threshold": temp,
            "datasourceUid": ALERT_DATASOURCE_UID,
        },
    ]


def render(temp):
    return TEMPLATE.format(
        temp=temp,
        retire=RETIRE_SOH_PCT,
        window=WINDOW_SECONDS,
        ds=ALERT_DATASOURCE_UID,
        soh_metric=SOH_METRIC,
        temp_metric=TEMP_METRIC,
    )


def main():

    temp = trained_peak_temperature_c()

    text = render(temp)

    for path in OUTPUTS:

        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)

        print(f"wrote {path.relative_to(ROOT)}")

    print(
        f"temperature bound: {temp:.4f} C "
        f"(max peak temperature in {CLEAN.name})"
    )


if __name__ == "__main__":

    main()
